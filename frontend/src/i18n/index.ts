export type TranslationKey = keyof typeof translations['en'];

export function useI18n() {
  const locale = computed(() => currentLocale.value);

  function setLocale(newLocale: Locale) {
    currentLocale.value = newLocale;
    localStorage.setItem(STORAGE_KEY, newLocale);
  }

  function toggleLocale() {
    setLocale(currentLocale.value === 'en' ? 'sv' : 'en');
  }

  function t(key: TranslationKey | string, params?: Record<string, string | number>): string {
    const dict = translations[currentLocale.value] as Record<string, string>;
    const fallbackDict = translations['en'] as Record<string, string>;
    let text = dict[key] || fallbackDict[key] || key;

    if (params) {
      for (const [paramKey, paramVal] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
      }
    }

    return text;
  }

  return {
    locale,
    setLocale,
    toggleLocale,
    t,
    isSwedish: computed(() => currentLocale.value === 'sv'),
  };
}
